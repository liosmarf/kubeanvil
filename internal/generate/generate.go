// Package generate renders every downstream input from cluster.yaml (ADR 0001):
// Terraform variables, the Ansible inventory and the GitOps cluster values.
package generate

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/netip"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v3"

	"github.com/liosmarf/kubeanvil/internal/catalog"
	"github.com/liosmarf/kubeanvil/internal/config"
)

const header = "# Generated by `kubeanvil generate` from cluster.yaml. Do not edit by hand.\n"

// Paths returns where each artefact of a cluster lives, relative to the repository root.
// Terraform and Ansible inputs stay local (clusters/ is git-ignored); the GitOps values must
// be committed, because Argo CD reads them from the repository.
func Paths(name string) (tfvars, inventory, gitops string) {
	return filepath.Join("clusters", name, "terraform.tfvars.json"),
		filepath.Join("clusters", name, "inventory"),
		filepath.Join("gitops", "clusters", name, "values.yaml")
}

// All writes every artefact under root and returns the files written.
func All(c *config.Cluster, cat *catalog.Catalog, root string) ([]string, error) {
	nodes, err := c.Nodes()
	if err != nil {
		return nil, err
	}
	prefix, err := netip.ParsePrefix(c.Spec.Network.CIDR)
	if err != nil {
		return nil, err
	}
	tfvars, inventory, gitops := Paths(c.Metadata.Name)
	files := map[string][]byte{}

	if files[tfvars], err = terraformVars(c, nodes, prefix.Bits()); err != nil {
		return nil, err
	}
	if files[filepath.Join(inventory, "hosts.yml")], err = ansibleHosts(c, nodes); err != nil {
		return nil, err
	}
	if files[filepath.Join(inventory, "group_vars", "all.yml")], err = ansibleVars(c, gitops); err != nil {
		return nil, err
	}
	if files[gitops], err = gitopsValues(c, cat, nodes); err != nil {
		return nil, err
	}

	var written []string
	for rel, data := range files {
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return nil, err
		}
		written = append(written, rel)
	}
	return written, nil
}

// --- Terraform -------------------------------------------------------------------------

type tfNode struct {
	Role        string `json:"role"`
	VMID        int    `json:"vm_id"`
	IPCIDR      string `json:"ip_cidr"`
	CPU         int    `json:"cpu"`
	MemoryMiB   int    `json:"memory_mib"`
	OSDiskGiB   int    `json:"os_disk_gib"`
	DataDiskGiB int    `json:"data_disk_gib"`
}

func terraformVars(c *config.Cluster, nodes []config.Node, bits int) ([]byte, error) {
	s, p := c.Spec, c.Spec.Provider.Proxmox
	tfNodes := map[string]tfNode{}
	for _, n := range nodes {
		tfNodes[n.Name] = tfNode{
			Role: string(n.Role), VMID: n.VMID, IPCIDR: fmt.Sprintf("%s/%d", n.IP, bits),
			CPU: n.Pool.CPU, MemoryMiB: n.Pool.MemoryMiB, OSDiskGiB: n.Pool.OSDiskGiB, DataDiskGiB: n.Pool.DataDiskGiB,
		}
	}
	vars := struct {
		ClusterName string `json:"cluster_name"`
		Proxmox     any    `json:"proxmox"`
		Image       any    `json:"image"`
		Network     any    `json:"network"`
		Access      any    `json:"access"`
		Nodes       any    `json:"nodes"`
	}{
		ClusterName: c.Metadata.Name,
		Proxmox: map[string]any{
			"endpoint": p.Endpoint, "insecure_tls": p.InsecureTLS, "ssh_user": p.SSHUser, "node": p.Node,
			"disk_datastore": p.Datastores.Disks, "image_datastore": p.Datastores.Images,
			"snippets_datastore": p.Datastores.Snippets, "bridge": p.Bridge,
		},
		Image: map[string]string{"url": s.Image.URL, "sha256": s.Image.SHA256},
		Network: map[string]any{
			"gateway": s.Network.Gateway, "dns_servers": s.Network.DNSServers, "search_domain": s.Network.SearchDomain,
		},
		Access: map[string]any{
			"admin_user": s.Access.AdminUser, "ssh_public_keys": s.Access.SSHPublicKeys, "timezone": timezone(c),
		},
		Nodes: tfNodes,
	}
	out, err := json.MarshalIndent(vars, "", "  ")
	return append(out, '\n'), err
}

// --- Ansible -----------------------------------------------------------------------------

func ansibleHosts(c *config.Cluster, nodes []config.Node) ([]byte, error) {
	group := func(role config.Role) map[string]any {
		hosts := map[string]any{}
		for _, n := range nodes {
			if n.Role == role {
				hosts[n.Name] = map[string]string{"ansible_host": n.IP.String(), "zone": c.Spec.Provider.Proxmox.Node}
			}
		}
		return map[string]any{"hosts": hosts}
	}
	return yamlDoc(map[string]any{"all": map[string]any{
		"vars":     map[string]string{"ansible_user": c.Spec.Access.AdminUser},
		"children": map[string]any{"control_plane": group(config.Server), "workers": group(config.Agent)},
	}})
}

func ansibleVars(c *config.Cluster, gitopsValues string) ([]byte, error) {
	s := c.Spec
	return yamlDoc(struct {
		AdminUser     string   `yaml:"base_admin_user"`
		AdminKeys     []string `yaml:"base_admin_ssh_keys"`
		Timezone      string   `yaml:"base_timezone"`
		K3sVersion    string   `yaml:"k3s_version"`
		APIVIP        string   `yaml:"k3s_api_vip"`
		ClusterCIDR   string   `yaml:"k3s_cluster_cidr"`
		ServiceCIDR   string   `yaml:"k3s_service_cidr"`
		LBStart       string   `yaml:"cilium_lb_range_start"`
		LBStop        string   `yaml:"cilium_lb_range_stop"`
		RepoURL       string   `yaml:"argocd_repo_url"`
		RepoRevision  string   `yaml:"argocd_repo_revision"`
		ClusterValues string   `yaml:"argocd_cluster_values"`
	}{
		s.Access.AdminUser, s.Access.SSHPublicKeys, timezone(c),
		s.Kubernetes.Version, s.Network.APIVIP, s.Network.PodCIDR, s.Network.ServiceCIDR,
		s.Network.LoadBalancerRange.Start, s.Network.LoadBalancerRange.End,
		s.GitOps.RepoURL, s.GitOps.Revision, filepath.ToSlash(gitopsValues),
	})
}

// --- GitOps ------------------------------------------------------------------------------

func gitopsValues(c *config.Cluster, cat *catalog.Catalog, nodes []config.Node) ([]byte, error) {
	s := c.Spec
	var cpIPs []string
	workers := 0
	for _, n := range nodes {
		if n.Role == config.Server {
			cpIPs = append(cpIPs, n.IP.String())
		} else {
			workers++
		}
	}
	dns := map[string]string{"provider": s.DNS.Provider}
	if r := s.DNS.RFC2136; r != nil && s.DNS.Provider == "rfc2136" {
		dns["server"], dns["zone"] = r.Server, r.Zone
	}
	backup := map[string]any{"s3": map[string]string{}}
	if b := s.Backup.S3; b != nil {
		backup["s3"] = map[string]string{"endpoint": b.Endpoint, "region": b.Region, "bucket": b.Bucket}
	}
	return yamlDoc(map[string]any{
		"cluster": map[string]any{
			"name": c.Metadata.Name, "apiVip": s.Network.APIVIP, "controlPlaneIps": cpIPs,
			"storageReplicas": min(3, max(workers, 1)), "domain": s.DNS.BaseDomain,
			"loadBalancerRange": map[string]string{"start": s.Network.LoadBalancerRange.Start, "stop": s.Network.LoadBalancerRange.End},
			"timezone":          timezone(c), "dns": dns,
			"tls":    map[string]string{"issuer": s.TLS.Issuer, "acmeEmail": s.TLS.ACMEEmail},
			"backup": backup,
		},
		"gitops":     map[string]string{"repoUrl": s.GitOps.RepoURL, "revision": s.GitOps.Revision},
		"components": cat.Selection(s.Components),
	})
}

// --- helpers -----------------------------------------------------------------------------

func timezone(c *config.Cluster) string {
	if c.Spec.Access.Timezone != "" {
		return c.Spec.Access.Timezone
	}
	return "UTC"
}

func yamlDoc(v any) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), enc.Close()
}
